  const englishStatus = document.getElementById("status-preview-en");
  const chineseStatus = document.getElementById("status-preview-zh");
  const windowPreview = document.getElementById("window-preview-image");
  let currentLanguage = "en";

  function setMeta(id, value) {
    const element = document.getElementById(id);
    if (element) element.setAttribute("content", value);
  }

  function applyLanguage(language) {
    const selected = copy[language];
    const chinese = language === "zh";
    currentLanguage = language;

    document.documentElement.lang = chinese ? "zh-CN" : "en";
    document.title = selected.title;
    toggle.lang = "zh-CN";

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const value = selected[element.dataset.i18n];
      if (value !== undefined) element.textContent = value;
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      const value = selected[element.dataset.i18nAriaLabel];
      if (value !== undefined) element.setAttribute("aria-label", value);
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
      const value = selected[element.dataset.i18nAlt];
      if (value !== undefined) element.setAttribute("alt", value);
    });

    setMeta("meta-description", selected.description);
    setMeta("og-locale", selected.locale);
    setMeta("og-site-name", selected.siteName);
    setMeta("og-title", selected.ogTitle);
    setMeta("og-description", selected.ogDescription);
    setMeta("og-image", selected.imageUrl);
    setMeta("og-image-alt", selected.windowAlt);
    setMeta("twitter-title", selected.twitterTitle);
    setMeta("twitter-description", selected.twitterDescription);
    setMeta("twitter-image", selected.imageUrl);
    setMeta("twitter-image-alt", selected.windowAlt);

    englishStatus.hidden = chinese;
    chineseStatus.hidden = !chinese;
    windowPreview.src = selected.image;
  }

